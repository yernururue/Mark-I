"""
common.py — Общие форматы данных.

Что такое Pydantic и модели?
В Python можно передавать данные просто в словарях (dict), например: {"code": "123"}.
Но это опасно: мы можем опечататься в названии ключа или передать число вместо строки.
Библиотека Pydantic позволяет создавать строгие правила (Схемы или Модели). 
Она проверяет (валидирует), что данные точно соответствуют нашим правилам.
"""
from datetime import datetime

# BaseModel — это основа для создания любых правил. 
# Наследуясь от нее, мы говорим Pydantic: "Следи за типами данных внутри этого класса".
from pydantic import BaseModel


class ErrorDetail(BaseModel):
    """
    Внутренняя структура ошибки.
    Здесь мы жестко задаем, что ошибка всегда состоит из кода и сообщения, и оба они — строки (str).
    """
    code: str       # Машинный код ошибки. Например: "UNAUTHORIZED" (нет доступа)
    message: str    # Понятный текст для человека. Например: "Ваш токен устарел"


class ErrorResponse(BaseModel):
    """
    Формат ответа, если что-то пошло не так.
    Мы всегда заворачиваем ошибку внутрь ключа "error". 
    Это удобно для фронтенда: разработчик всегда знает, где искать причину поломки.
    """
    error: ErrorDetail


class HealthResponse(BaseModel):
    """
    Ответ для эндпоинта Health Check (Проверка здоровья).
    Что такое Health Check? 
    Это как пульс у человека. Облачные системы (например, Google Cloud) 
    раз в минуту стучатся по адресу /health. Если сервер отвечает "status: ok", 
    значит он жив и на него можно отправлять реальных пользователей. 
    Если ответа нет — сервер "умер", и облако его автоматически перезагрузит.
    """
    status: str           # Всегда будет возвращать "ok"
    version: str          # Текущая версия нашего кода (помогает понять, обновился ли сервер)
    timestamp: datetime   # Точное время, когда сервер ответил на запрос
